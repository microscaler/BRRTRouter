"""Shared utilities for calling BRRTRouter generate commands.

Which ``brrtrouter-gen`` runs is decided by :func:`generator_command`: the generator at the BRRTRouter rev the
consumer's services build against, not whatever a sibling checkout happens to hold. Code generated by another rev
drifts from what the services compile against (templates change between revs).
"""

from __future__ import annotations

import os
import re
import subprocess
from pathlib import Path

GIT_URL = "https://github.com/microscaler/BRRTRouter.git"

# `brrtrouter = { git = "…/BRRTRouter.git", rev = "<sha>" … }` in a consumer's Cargo.toml
_PIN = re.compile(
    r'^brrtrouter\s*=\s*\{[^}\n]*git\s*=\s*"[^"]*/BRRTRouter(?:\.git)?"[^}\n]*rev\s*=\s*"([0-9a-f]{7,40})"',
    re.MULTILINE,
)


def find_brrtrouter(project_root: Path, brrtrouter_path: Path | None = None) -> tuple[Path, Path]:
    """Find BRRTRouter binary and manifest paths.

    Returns (brrtrouter_bin_path, manifest_path).
    Raises FileNotFoundError if BRRTRouter not found.
    """
    if brrtrouter_path is None:
        brrtrouter_path = project_root.parent / "BRRTRouter"

    brrtrouter_bin = brrtrouter_path / "target" / "debug" / "brrtrouter-gen"
    manifest = brrtrouter_path / "Cargo.toml"

    if not manifest.exists():
        msg = f"BRRTRouter not found at {brrtrouter_path}"
        raise FileNotFoundError(msg)

    return brrtrouter_bin, manifest


def pinned_rev(project_root: Path) -> str | None:
    """The BRRTRouter rev the consumer's services build against (its Cargo.toml, or microservices/Cargo.toml)."""
    for manifest in (project_root / "Cargo.toml", project_root / "microservices" / "Cargo.toml"):
        if manifest.exists():
            m = _PIN.search(manifest.read_text())
            if m:
                return m.group(1)
    return None


def _checkout_head(path: Path) -> str | None:
    if not (path / ".git").exists():
        return None
    r = subprocess.run(
        ["git", "-C", str(path), "rev-parse", "HEAD"], check=False, capture_output=True, text=True
    )
    return r.stdout.strip() if r.returncode == 0 and r.stdout else None


def _cargo_run(manifest: Path) -> list[str]:
    return ["cargo", "run", "--manifest-path", str(manifest), "--bin", "brrtrouter-gen", "--"]


def generator_command(project_root: Path, brrtrouter_path: Path | None = None) -> list[str]:
    """The command prefix that runs ``brrtrouter-gen``, chosen in this order:

    1. ``BRRTROUTER_GEN`` (a path to a binary): a deliberate local build.
    2. ``BRRTROUTER_GEN_LOCAL=1``: the local BRRTRouter checkout (``cargo run``), whatever its rev.
    3. The consumer pins a rev (``brrtrouter = { git = …, rev = … }``):
       - ``brrtrouter-gen`` installed at that rev under ``BRRTROUTER_GEN_CACHE`` (default
         ``~/.cache/brrtrouter-gen``)/<rev>, as a consumer's spec-lint script installs it;
       - else the local checkout, when its HEAD is that rev;
       - else it is installed there now (``cargo install --locked --git … --rev …``), and refused with an
         explanation when that fails.
    4. No pin (a path dependency, or no Cargo.toml): the local checkout, as before.
    """
    explicit = os.environ.get("BRRTROUTER_GEN")
    if explicit:
        return [explicit]
    local = brrtrouter_path or project_root.parent / "BRRTRouter"
    rev = pinned_rev(project_root)
    if os.environ.get("BRRTROUTER_GEN_LOCAL") == "1" or rev is None:
        _bin, manifest = find_brrtrouter(project_root, local)
        return _cargo_run(manifest)

    root = (
        Path(os.environ.get("BRRTROUTER_GEN_CACHE", Path.home() / ".cache" / "brrtrouter-gen"))
        / rev
    )
    installed = root / "bin" / "brrtrouter-gen"
    if installed.exists():
        return [str(installed)]
    head = _checkout_head(local) if (local / "Cargo.toml").exists() else None
    if head is not None and head.startswith(rev):
        return _cargo_run(local / "Cargo.toml")

    print(f"installing brrtrouter-gen at BRRTRouter {rev} into {root}")
    r = subprocess.run(
        [
            "cargo",
            "install",
            "--quiet",
            "--locked",
            "--git",
            GIT_URL,
            "--rev",
            rev,
            "--bin",
            "brrtrouter-gen",
            "--root",
            str(root),
            "brrtrouter",
        ],
        check=False,
    )
    if r.returncode == 0 and installed.exists():
        return [str(installed)]
    where = f"{local} is at {head}" if head else f"no BRRTRouter checkout at {local}"
    msg = (
        f"The services pin BRRTRouter {rev}, but brrtrouter-gen at that rev is not installed and could not be "
        f"installed into {root}, and {where}. Generating with another rev drifts from what the services build "
        f"against. Install it, check out {rev} in {local}, or set BRRTROUTER_GEN_LOCAL=1 to use the local "
        "checkout deliberately."
    )
    raise RuntimeError(msg)


def call_brrtrouter_generate(
    spec_path: Path,
    output_dir: Path,
    project_root: Path,
    brrtrouter_path: Path | None = None,
    deps_config_path: Path | None = None,
    package_name: str | None = None,
    capture_output: bool = False,
) -> subprocess.CompletedProcess:
    """Call BRRTRouter's generate command to generate gen crate.

    Args:
        spec_path: Path to OpenAPI spec file
        output_dir: Output directory for gen crate
        project_root: Consumer project root (cwd; its Cargo.toml names the BRRTRouter rev)
        brrtrouter_path: Optional path to BRRTRouter (defaults to ../BRRTRouter)
        deps_config_path: Optional path to brrtrouter-dependencies.toml
        package_name: Optional [package].name for generated Cargo.toml (e.g. acme_accounting_financial_reports_gen)
        capture_output: Whether to capture stdout/stderr

    Returns:
        CompletedProcess from subprocess.run
    """
    deps_config_arg = []
    if deps_config_path and deps_config_path.exists():
        deps_config_arg = ["--dependencies-config", str(deps_config_path)]
    package_name_arg = []
    if package_name:
        package_name_arg = ["--package-name", package_name]
    cmd = [
        *generator_command(project_root, brrtrouter_path),
        "generate",
        "--spec",
        str(spec_path),
        "--output",
        str(output_dir),
        "--force",
        *deps_config_arg,
        *package_name_arg,
    ]
    return subprocess.run(
        cmd,
        check=False,  # Let caller handle errors
        cwd=str(project_root),
        capture_output=capture_output,
        text=True,
    )


def call_brrtrouter_generate_stubs(
    spec_path: Path,
    impl_dir: Path,
    component_name: str,
    project_root: Path,
    brrtrouter_path: Path | None = None,
    force: bool = False,
    sync: bool = False,
    capture_output: bool = False,
) -> subprocess.CompletedProcess:
    """Call BRRTRouter's generate-stubs command to generate impl crate.

    Args:
        spec_path: Path to OpenAPI spec file
        impl_dir: Output directory for impl crate
        component_name: Component name (gen crate name) for --component-name
        project_root: Consumer project root (cwd; its Cargo.toml names the BRRTRouter rev)
        brrtrouter_path: Optional path to BRRTRouter (defaults to ../BRRTRouter)
        force: Whether to force overwrite existing stubs (skipped when sentinel present)
        sync: When true, only patch existing stubs that have the user-owned sentinel
        capture_output: Whether to capture stdout/stderr

    Returns:
        CompletedProcess from subprocess.run
    """
    cmd = [
        *generator_command(project_root, brrtrouter_path),
        "generate-stubs",
        "--spec",
        str(spec_path),
        "--output",
        str(impl_dir),
        "--component-name",
        component_name,
    ]
    if force:
        cmd.append("--force")
    if sync:
        cmd.append("--sync")
    return subprocess.run(
        cmd,
        check=False,  # Let caller handle errors
        cwd=str(project_root),
        capture_output=capture_output,
        text=True,
    )
